"""Versioned services available to UI plugins; implementations belong to the host."""
from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol

PLUGIN_API_VERSION = 1


class PluginServices(Protocol):
    @property
    def parent_widget(self) -> Any: ...
    def selected_folder(self) -> Path | None: ...
    def data_folder(self) -> Path | None: ...
    def recent_folders(self) -> list[str]: ...
    def set_data_folder(self, folder: str | Path) -> None: ...
    def refresh_navigator(self) -> None: ...
    def log(self, message: str, level: str = "info") -> None: ...
    def submit_job(self, operation: str, folder: Path, *, recursive: bool = False,
                   parameters: dict[str, Any] | None = None) -> None: ...
